k <- jwk_oct(as.raw(1:32), kid = "k1")
show <- function(label, expr) { r <- try_(expr); cat(label, ": "); if (inherits(r, "err")) cat("ERR", r$cls[1], r$msg, "\n") else { p <- strsplit(r, ".", fixed = TRUE)[[1]]; cat(rawToChar(zujose:::b64url_decode(p[1], "x", NULL)), rawToChar(zujose:::b64url_decode(p[2], "x", NULL)), "\n"); add(label = label, token = r) } }
