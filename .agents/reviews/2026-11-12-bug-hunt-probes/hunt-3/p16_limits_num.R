source("pre.R")
k <- jwk_oct(as.raw(1:32)); t <- jws_sign("payload", k, "HS256"); kw <- jwk_oct(as.raw(1:16)); pw <- jwk_oct(charToRaw("pw"))
e <- jwe_encrypt("x", pw, "PBES2-HS256+A128KW", header = list(p2c = 1000))
R <- function(label, expr) { r <- try_(expr); cat(sprintf("%-34s", label)); if (inherits(r, "err")) cat("ERR", r$cls[1], "|", r$msg, "\n") else cat("ok\n") }
for (v in list(NA, NA_real_, -1, 0, 1.5, Inf, "10", NULL, c(1, 2), TRUE, 2^53, NaN)) R(paste("limits token =", deparse(v)), jws_verify(t, k, "HS256", limits = jose_limits(token = v)))
R("token = nchar", jws_verify(t, k, "HS256", limits = jose_limits(token = nchar(t))))
R("token = nchar-1", jws_verify(t, k, "HS256", limits = jose_limits(token = nchar(t) - 1)))
R("payload = 7", jws_verify(t, k, "HS256", limits = jose_limits(payload = 7)))
R("payload = 6", jws_verify(t, k, "HS256", limits = jose_limits(payload = 6)))
R("header = 15", jws_verify(t, k, "HS256", limits = jose_limits(header = 15)))
R("header = 14", jws_verify(t, k, "HS256", limits = jose_limits(header = 14)))
R("signatures = 0 compact", jws_verify(t, k, "HS256", limits = jose_limits(signatures = 0)))
R("p2c = 1000", jwe_decrypt(e, pw, "PBES2-HS256+A128KW", "A128CBC-HS256", limits = jose_limits(p2c = 1000)))
R("p2c = 999", jwe_decrypt(e, pw, "PBES2-HS256+A128KW", "A128CBC-HS256", limits = jose_limits(p2c = 999)))
R("p2c = 999.5", jwe_decrypt(e, pw, "PBES2-HS256+A128KW", "A128CBC-HS256", limits = jose_limits(p2c = 999.5)))
R("p2c = Inf", jwe_decrypt(e, pw, "PBES2-HS256+A128KW", "A128CBC-HS256", limits = jose_limits(p2c = Inf)))
R("limits list()", jws_verify(t, k, "HS256", limits = list()))
R("limits NULL", jws_verify(t, k, "HS256", limits = NULL))
