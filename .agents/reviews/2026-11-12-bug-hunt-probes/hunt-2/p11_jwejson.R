# build: prot = JSON text or NULL; aad raw/NULL; extra = raw JSON members text
mk <- function(prot, extra = "", aad = NULL, pt = "secret", aad_member = TRUE, prot_member = NULL) {
  pb <- if (is.null(prot)) "" else b64(prot)
  a <- charToRaw(pb); if (!is.null(aad)) a <- c(a, charToRaw("."), charToRaw(b64(aad)))
  iv <- as.raw(1:12); s <- zucrypt::crypt_aes_gcm_encrypt(charToRaw(pt), CEK, iv, aad = a)
  m <- c(if (!is.null(prot)) sprintf('"protected":"%s"', pb), prot_member, if (!is.null(aad) && aad_member) sprintf('"aad":"%s"', b64(aad)),
    sprintf('"iv":"%s"', b64(iv)), sprintf('"ciphertext":"%s"', b64(as.vector(s))), sprintf('"tag":"%s"', b64(attr(s, "tag"))), if (nzchar(extra)) extra)
  paste0("{", paste(m, collapse = ","), "}")
}
