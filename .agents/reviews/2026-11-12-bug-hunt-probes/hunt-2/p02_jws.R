# sig variants
parts <- strsplit(tok, ".", fixed = TRUE)[[1]]
v("empty sig", paste0(parts[1], ".", parts[2], "."))
sig <- unb64(parts[3])
v("trunc sig", paste0(parts[1], ".", parts[2], ".", b64(sig[1:16])))
v("sig + byte", paste0(parts[1], ".", parts[2], ".", b64(c(sig, as.raw(0)))))
v("sig padded", paste0(tok, "="))
# noncanonical b64 of sig: change last char's trailing bits
last <- substr(parts[3], nchar(parts[3]), nchar(parts[3])); cat("last char", last, "\n")
alph <- strsplit("ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789-_", "")[[1]]
i <- match(last, alph) - 1; alt <- alph[bitwOr(i, 1) + 1]
v("noncanon sig", paste0(substr(tok, 1, nchar(tok) - 1), alt))
v("std alphabet payload", paste0(parts[1], ".", "aGVsbG8+", ".", parts[3]))
