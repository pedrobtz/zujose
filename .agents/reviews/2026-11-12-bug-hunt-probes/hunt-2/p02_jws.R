key <- jwk_oct(K32)
v <- function(label, tok, ..., algorithms = "HS256", k = key) try_(label, jws_verify(tok, k, algorithms = algorithms, ...))
tok <- hs('{"alg":"HS256"}', "hello", K32)
r <- v("base", tok); stopifnot(rawToChar(r$payload) == "hello")
v("trailing dot", paste0(tok, "."))
v("leading ws", paste0(" ", tok)); v("trailing nl", paste0(tok, "\n"))
v("dup alg", hs('{"alg":"HS256","alg":"HS256"}', "x", K32))
v("alg none", paste0(b64('{"alg":"none"}'), ".", b64("x"), "."), algorithms = "HS256")
try_("algorithms none", jws_verify(tok, key, algorithms = "none"))
try_("algorithms missing", jws_verify(tok, key))
v("alg lower", hs('{"alg":"hs256"}', "x", K32))
v("alg number", hs('{"alg":256}', "x", K32))
v("hdr ws + bom", hs('﻿{"alg":"HS256"}', "x", K32))
v("hdr ws", hs(' {"alg" : "HS256" }\n', "x", K32))
v("hdr array", hs('["alg","HS256"]', "x", K32))
v("hdr escaped alg name", hs('{"\\u0061lg":"HS256"}', "x", K32))
