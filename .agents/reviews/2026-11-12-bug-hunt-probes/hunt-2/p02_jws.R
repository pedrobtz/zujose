v("detached wrong", dt, payload = "hellO")
v("payload given but carried", tok, payload = "hello")
dtf <- { s <- zucrypt::crypt_hmac(c(charToRaw(paste0(h, ".")), charToRaw("a.b.c")), K32, "sha256"); paste0(h, "..", b64(s)) }
r <- v("detached b64false dots", dtf, payload = "a.b.c"); if (is.list(r)) print(rawToChar(r$payload))
