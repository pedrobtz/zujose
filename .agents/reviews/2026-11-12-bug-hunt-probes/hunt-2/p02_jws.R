mk <- function(h, p) paste0(h, ".", p, ".", b64(zucrypt::crypt_hmac(charToRaw(paste0(h, ".", p)), K32, "sha256")))
r <- v("b64false", mk(h, "$.02")) 
r <- v("b64false plain", mk(h, "hello world")); if (is.list(r)) print(rawToChar(r$payload))
r <- v("b64false utf8", mk(h, "héllo")); if (is.list(r)) print(r$payload)
# detached
dt <- sub("\\.[^.]*\\.", "..", tok)
