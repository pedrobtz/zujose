source("../hunt-1/pre.R")
T <- function(label, expr) { cat("==", label, ": "); r <- tryCatch(expr, error=function(e) paste0("ERROR<", class(e)[1], "> ", conditionMessage(e))); cat(if (is.character(r)) r else format(r), "\n") }
k <- key
tok <- jwt_encode(list(scope="read"), k, "HS256")
T("F1 dup claims spec accepted", { r <- jwt_decode(tok, k, "HS256", claims=list(scope="read", scope="write")); "ACCEPTED" })
k0 <- jwk_oct(as.raw(1:32), key_ops=character())
T("F2 k0 sign", { jws_sign("x", k0, "HS256"); "signed" })
T("F2 roundtrip sign", { jws_sign("x", as_jwk(jwk_json(k0, TRUE)), "HS256"); "signed" })
T("F3 named expires_in", payload_of(jwt_encode(list(), k, "HS256", expires_in=c(ttl=60))))
T("F4 named signers", jws_sign("x", list(a=jws_signer(k,"HS256")), format="general"))
kw <- jwk_oct(as.raw(1:16))
T("F5 zip unprotected", { t <- jwe_encrypt("x", kw, "A128KW", format="flattened", unprotected=list(zip="DEF")); substr(t,1,200) })
T("F6 nested dup", payload_of(jwt_encode(list(o=c(a=1,a=2)), k, "HS256")))
T("F6 dup header", header_of(jwt_encode(list(), k, "HS256", header=list(typ="JWT", typ="x"))))
T("F7 payload 11 at 10", { t <- jws_sign(strrep("a",11), k, "HS256"); jws_verify(t, k, "HS256", limits=jose_limits(payload=10)); "ACCEPTED" })
T("F8 OutDec", { op <- options(OutDec=","); on.exit(options(op)); withCallingHandlers(capture.output(print(jose_limits())), warning=function(w) {cat("WARN:", conditionMessage(w), " "); invokeRestart("muffleWarning")}); "printed" })
T("F9 kidnap print", { t <- jws_sign(zujson::json_write(list(a=1)), k, "HS256", header=list(kidnap="zzz")); capture.output(print(jwt_decode(t, jwk_oct(as.raw(1:32)), "HS256")))[1] })
pw <- jwk_oct(charToRaw("password-password"))
T("F9 p2count", { t <- jwe_encrypt("x", pw, "PBES2-HS256+A128KW", header=list(p2count=1234)); header_of(t) })
T("F10 peek detached payload", { p <- jose_peek(jws_sign("hello", k, "HS256", detached=TRUE)); paste(class(p$payload), length(p$payload), is.null(p$signing_input)) })
T("F11 key_ops vector list", { as_jwk(list(kty="oct", k="AQIDBAUGBwgJCgsMDQ4PEBESExQVFhcYGRobHB0eHyA", key_ops=c("sign","verify"))); "ok" })
T("F12 enc vector", { jwe_encrypt("x", kw, "A128KW", enc=c("A128GCM","A256GCM")); "ok" })
T("F12 RSA 2049", { jwk_generate("RSA", size=2049); "ok" })
T("F13 set[NA] print", { s <- jwk_set(k, kw); capture.output(print(s[NA])); "printed" })
T("F14 generate oct PBES2", { jwk_generate("oct", alg="PBES2-HS256+A128KW"); "ok" })
T("F15 unknown kty print", capture.output(print(as_jwk('{"kty":"foo","k":"AQID"}'))) |> paste(collapse=" | "))
T("F16 member order", { t <- jwt_encode(list(o=list(a=1,b=2)), k, "HS256"); jwt_decode(t, k, "HS256", claims=list(o=list(b=2,a=1))); "ACCEPTED" })
T("F17 recipient alg", { r <- jwe_recipient(kw, header=list(alg="A256KW")); t <- jwe_encrypt("x", list(r), format="general"); substr(t, 1, 300) })
T("F18 jwt_encode signer list", { jwt_encode(list(a=1), list(jws_signer(k,"HS256"))); "ok" })
T("F19 named issuer", { t <- jwt_encode(list(iss="me"), k, "HS256"); jwt_decode(t, k, "HS256", issuer=c(x="me")); "ACCEPTED" })
