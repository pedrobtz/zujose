P <- function(label, expr) { cat("---", label, ": "); r <- try_(expr); if (!is.null(r)) { if (is.character(r)) cat(r, sep = "\n") else try_(print(r)) }; invisible(r) }
k0 <- jwk_oct(as.raw(1:32), key_ops = character())
P("key_ops empty: sign refused", jws_sign("x", k0, "HS256"))
j <- jwk_json(k0, TRUE); cat(j, "\n")
P("after JSON roundtrip: sign", jws_sign("x", as_jwk(j), "HS256"))

rsa <- jwk_generate("RSA", kid = "r1", alg = "RS256")
ec <- jwk_generate("EC", crv = "P-521")
okp <- jwk_generate("OKP")
for (k in list(rsa, ec, okp)) {
  cat("=====", k$kty, "\n")
  print(k); print(jwk_public(k))
  pubj <- jwk_json(k); cat(substr(pubj, 1, 80), "\n"); cat("public json members:", names(zujson::json_parse(pubj, simplify = "none")), "\n")
  prj <- jwk_json(k, TRUE); cat("private json members:", names(zujson::json_parse(prj, simplify = "none")), "\n")
  cat("json roundtrip identical:", identical(as_jwk(prj), k), " public:", identical(as_jwk(pubj), jwk_public(k)), "\n")
  pem <- jwk_pem(k, TRUE); pub <- jwk_pem(k)
  cat(substr(pem, 1, 30), "|", substr(pub, 1, 30), "\n")
  kp <- as_jwk(pem); cat("pem roundtrip members equal:", identical(kp$members[names(k$members)], k$members), "names:", names(kp$members), " bits:", kp$bits, k$bits, "\n")
  kpub <- as_jwk(pub); cat("pub pem equal:", identical(kpub$members, jwk_public(k)$members), "\n")
  cat("thumbprints equal (key, public, pem, json):", length(unique(c(jwk_thumbprint(k), jwk_thumbprint(jwk_public(k)), jwk_thumbprint(kp), jwk_thumbprint(as_jwk(prj))))) == 1, "\n")
  P("jwk_pem private from public", jwk_pem(jwk_public(k), TRUE))
  P("str of print shows secret?", any(grepl(k$members$d, capture.output(print(k)), fixed = TRUE)))
  P("format()", format(k)); P("toString", toString(k)); 
}
